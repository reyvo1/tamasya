import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, '..');
const argv = process.argv.slice(2);
const production = argv.includes('--production');

function arg(name, envName, fallback = '') {
  const prefix = `--${name}=`;
  const found = argv.find((v) => v.startsWith(prefix));
  return (found ? found.slice(prefix.length) : process.env[envName] || fallback).trim();
}

function normalizeHttpsUrl(raw, label, allowPath = false) {
  if (!raw) throw new Error(`${label} wajib diisi.`);
  let url;
  try { url = new URL(raw); } catch { throw new Error(`${label} bukan URL valid: ${raw}`); }
  if (production && url.protocol !== 'https:') throw new Error(`${label} production wajib HTTPS.`);
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error(`${label} hanya boleh http/https.`);
  url.hash = '';
  url.search = '';
  if (!allowPath && url.pathname !== '/' && url.pathname !== '') throw new Error(`${label} harus berupa origin tanpa path.`);
  const host = url.hostname.toLowerCase();
  if (production && /(^|[.-])(staging|stage|dev|test|example|localhost|local)([.-]|$)/i.test(host)) {
    throw new Error(`${label} masih terlihat sebagai host non-production: ${host}`);
  }
  return url;
}

const appRaw = arg('app-url', 'TAMASYA_APP_URL', process.env.APP_URL || 'https://app.nolink.my.id');
const siteRaw = arg('site-url', 'TAMASYA_PUBLIC_SITE_URL', process.env.PUBLIC_SITE_URL || 'https://tamasya.nolink.my.id');
const app = normalizeHttpsUrl(appRaw, 'APP URL');
const site = normalizeHttpsUrl(siteRaw, 'PUBLIC SITE URL');
const apiUrl = new URL('/api.php', app).toString();
const appOrigin = app.origin;
const siteOrigin = site.origin;

if (production && appOrigin === siteOrigin) {
  console.warn('PERINGATAN: APP URL dan PUBLIC SITE URL memakai origin yang sama. Pastikan ini memang topologi produksi yang diinginkan.');
}

const runtime = `(function () {\n  "use strict";\n\n  // Generated by scripts/apply-production-config.mjs. URLs only; never store secrets here.\n  const runtime = Object.freeze({\n    API_URL: ${JSON.stringify(apiUrl)},\n    SITE_URL: ${JSON.stringify(siteOrigin)}\n  });\n\n  window.TAMASYA_PUBLIC_RUNTIME = runtime;\n  window.TAMASYA_PUBLIC_API_URL = runtime.API_URL;\n  window.TAMASYA_PUBLIC_SITE_URL = runtime.SITE_URL;\n})();\n`;
fs.writeFileSync(path.join(root, 'runtime-config.js'), runtime);

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url>\n    <loc>${siteOrigin}/</loc>\n    <changefreq>weekly</changefreq>\n    <priority>1.0</priority>\n  </url>\n</urlset>\n`;
fs.writeFileSync(path.join(root, 'sitemap.xml'), sitemap);
fs.writeFileSync(path.join(root, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${siteOrigin}/sitemap.xml\n`);

const htPath = path.join(root, '.htaccess');
let ht = fs.readFileSync(htPath, 'utf8');
ht = ht.replace(/^# TAMASYA_API_ORIGIN:.*$/m, `# TAMASYA_API_ORIGIN: ${appOrigin} — prefer admin/tamasya_configurator.php; legacy Node/public_config_tool.php remain supported when domains change.`);
if (!/^# TAMASYA_API_ORIGIN:/m.test(ht)) {
  throw new Error('Marker TAMASYA_API_ORIGIN tidak ditemukan di .htaccess.');
}
const cspPattern = /connect-src 'self' [^;]+;/;
if (!cspPattern.test(ht)) throw new Error('connect-src CSP tidak ditemukan di .htaccess.');
ht = ht.replace(cspPattern, `connect-src 'self' ${appOrigin};`);
fs.writeFileSync(htPath, ht);

console.log(`Public config OK: site=${siteOrigin} api=${apiUrl}`);
console.log(`CSP connect-src dibatasi ke: ${appOrigin}`);
