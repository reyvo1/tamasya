import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read = path => fs.readFileSync(new URL('../'+path,import.meta.url),'utf8');
const rooms=read('assets/chunks/rooms.js');
const helper=rooms.match(/^const pr=\(p,n,r\)=>[^;]+;/m);
assert.ok(helper,'Actual UI room quote helper found');
const quote=new Function(helper[0]+'return pr;')();
assert.equal(quote(227273,1,10),250000);
assert.equal(quote(227273,2,10),500000);
assert.equal(quote(227273,3,10),750000);
assert.equal(quote(227272.73,1,10),250000);
assert.equal(quote(200000,1,0),200000);
assert.equal(quote(227273,1,11),252273);
const quoteStart=rooms.indexOf('let Ir,Qr,Ws;');
const quoteEnd=rooms.indexOf('const mc=',quoteStart);
assert.ok(quoteStart>0 && quoteEnd>quoteStart,'Exact shipped room-booking quote body found');
const calculateWeb=new Function('V','im','D','W','mi','Qe','window','pr',
 rooms.slice(quoteStart,quoteEnd)+';return {base:Ir,tax:Qr,gross:Ws};');
const master=calculateWeb({price:227273},1,'total','',true,10,{},quote);
assert.equal(master.gross,250000);
assert.equal(master.base,227272.73);
assert.equal(master.tax,22727.27);
assert.equal(calculateWeb({price:227273},2,'total','',true,10,{},quote).gross,500000);
assert.equal(calculateWeb({price:227273},1,'total','250000.30',true,10,{},quote).gross,250000.30);
assert.equal(calculateWeb({price:227273},1,'base','227273',true,10,{},quote).gross,250000.30);
assert.equal(calculateWeb({price:227273},1,'total','',false,0,{},quote).gross,227273);
assert.ok(rooms.includes('W?+W:pr(Number(V?.price||0),im,mi?Qe:0)'),'Web default reservation uses published master quote');
assert.ok(rooms.includes('Ws=W?+W:pr('),'Explicit total nett remains direct user gross input');
assert.ok(rooms.includes('D==="base"&&W){Ir=+W'),'Manual pre-tax amount retains explicit cents');
assert.ok(rooms.includes('pr(V.price,pt,en?Nt:0)'),'Web room extension uses nightly master quote');
console.log('Published room nett JS pricing: 16+ assertions PASS.');
